// ADX-System fork only: copy a snapshot of adxs-ui (ADX-System/adxs-ui, react/) into packages/adxs-ui so the docsite
// documents our components next to astryx's. Run before building the docsite:
//   node scripts/sync-adxs-ui.mjs [path to adxs-ui/react]   (default ~/workspace/adxs-ui/react)
// adxs-ui stays the source of truth; packages/adxs-ui is generated (git-ignored) and never edited by hand.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const SRC = path.resolve(process.argv[2] ?? path.join(os.homedir(), 'workspace/adxs-ui/react'));
const ROOT = path.resolve(import.meta.dirname, '..');
const DEST = path.join(ROOT, 'packages/adxs-ui');
const pkg = JSON.parse(fs.readFileSync(path.join(SRC, 'package.json'), 'utf8'));
if (pkg.name !== '@adxs/ui') throw new Error(`${SRC} is not @adxs/ui (found ${pkg.name})`);
if (!fs.existsSync(path.join(SRC, 'dist-integration/adxs-ui.css'))) throw new Error('run `npm run build:integration-css` in adxs-ui/react first');

fs.rmSync(DEST, {recursive: true, force: true});
const copy = rel => fs.cpSync(path.join(SRC, rel), path.join(DEST, rel), {recursive: true});
for (const rel of ['astryx.integration.mjs', 'dist-integration', 'src/components', 'src/lib']) copy(rel);

// '@/x' (adxs-ui's tsconfig alias for src/) -> a relative path, so the copy builds without that alias
const walk = dir => fs.readdirSync(dir, {withFileTypes: true}).flatMap(d => d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]);
let rewritten = 0;
for (const file of walk(path.join(DEST, 'src')).filter(f => /\.(ts|tsx)$/.test(f))) {
  const text = fs.readFileSync(file, 'utf8');
  const next = text.replace(/(from\s+|import\s*\(\s*)(['"])@\/([^'"]+)\2/g, (_, pre, q, spec) => {
    let rel = path.relative(path.dirname(file), path.join(DEST, 'src', spec));
    if (!rel.startsWith('.')) rel = './' + rel;
    return `${pre}${q}${rel}${q}`;
  });
  if (next !== text) { fs.writeFileSync(file, next); rewritten++; }
}

// The docsite reads each doc's named export `docs`; integration docs written by `astryx integration add` use a default
// export. Give the copies both, so the CLI and the docsite read the same object.
for (const doc of walk(path.join(DEST, 'src/components')).filter(f => f.endsWith('.doc.mjs'))) {
  const text = fs.readFileSync(doc, 'utf8');
  if (/export const docs\b/.test(text)) continue;
  fs.writeFileSync(doc, text.replace(/export default\s*\{/, 'export const docs = {') + '\nexport default docs;\n');
}

// Package root: re-export every documented component (the names astryx Core owns are not documented, so they are not
// exported here and never shadow Core in the docsite playground)
const docs = walk(path.join(DEST, 'src/components')).filter(f => f.endsWith('.doc.mjs'));
const lines = [];
for (const doc of docs) {
  const text = fs.readFileSync(doc, 'utf8');
  const spec = /import:\s*'@adxs\/ui\/([^']+)'/.exec(text)?.[1];
  if (!spec) continue;
  const names = [...new Set([...text.matchAll(/^\s{2,6}name:\s*'([A-Z]\w*)'/gm)].map(m => m[1]))];
  const target = pkg.exports['./' + spec].replace(/^\.\/src\//, './').replace(/\.tsx?$/, '');
  lines.push(`export { ${names.join(', ')} } from '${target}';`);
}
fs.writeFileSync(path.join(DEST, 'src/index.ts'), '// generated by scripts/sync-adxs-ui.mjs\n' + lines.sort().join('\n') + '\n');

// UI ledger (ADX-System/adxs-ui ledger/, API 127.0.0.1:8126) -> an "ADXS" docs section with one "UI 대장" page:
// every component's status, origin, terms check and where it is used. The site build fails if the ledger is
// unreachable, so the site never silently shows a stale ledger.
const LEDGER = process.env.UI_LEDGER_URL ?? 'http://127.0.0.1:8126';
const ledger = await fetch(`${LEDGER}/export`).then(r => { if (!r.ok) throw new Error(`ui-ledger ${r.status}`); return r.json(); })
  .catch(e => { throw new Error(`UI ledger unreachable at ${LEDGER} (${e.message}) — start ui-ledger.service`); });
const STATUS = {surveyed: '조사', decomposed: '분해됨', assembled: '조립됨', registered: '등록됨', in_use: '쓰는 중', on_hold: '보류'};
const TERMS = {allowed: '허용', forbidden: '금지', open_source: '공개 소스', own_design: '자체 설계', unchecked: '확인 안 함'};
const cell = v => String(v ?? '').replaceAll('|', '/');
fs.mkdirSync(path.join(DEST, 'docs'), {recursive: true});
fs.writeFileSync(path.join(DEST, 'docs/adxs.doc.mjs'), `// generated by scripts/sync-adxs-ui.mjs
export default ${JSON.stringify({type: 'namespace', name: 'adxs', title: 'ADXS',
  summary: 'ADX System 의 부품(@adxs/ui)과 UI 대장.', slots: {guides: {title: 'Guides', accepts: {kinds: ['generic']}}}}, null, 2)};
`);
const byStatus = Object.entries(STATUS).map(([k, label]) => [label, ledger.filter(c => c.status === k).length]).filter(([, n]) => n);
fs.writeFileSync(path.join(DEST, 'docs/ui-ledger.doc.mjs'), `// generated by scripts/sync-adxs-ui.mjs from the UI ledger API
export default ${JSON.stringify({
  type: 'generic', name: 'ui-ledger', title: 'UI 대장',
  description: '@adxs/ui 부품마다 어디서 왔고(출처 · 라이선스 · 약관 확인) 지금 어느 단계이며 어느 화면이 쓰는지.',
  placement: {parent: 'namespace:adxs', slot: 'guides', order: 10},
  sections: [
    {id: 'summary', title: '요약', content: [
      {type: 'prose', text: `부품 ${ledger.length}개 — ` + byStatus.map(([l, n]) => `${l} ${n}`).join(' · ') + '. 단계는 조사 → 분해됨 → 조립됨 → 등록됨 → 쓰는 중이고, 대장은 `ui-ledger` CLI · API 로만 고친다.'},
    ]},
    {id: 'components', title: '부품', content: [
      {type: 'table', headers: ['부품', '단계', '출처', '라이선스', '약관 확인', '쓰는 곳'],
       rows: ledger.map(c => [c.name, STATUS[c.status] ?? c.status,
         cell(c.sources.map(s => s.product).join(', ')), cell(c.sources.map(s => s.license).join(', ')),
         cell(c.sources.map(s => TERMS[s.terms_result] ?? s.terms_result).join(', ')), String(c.usage.length)])},
    ]},
  ],
}, null, 2)};
`);
fs.writeFileSync(path.join(DEST, 'astryx.integration.mjs'),
  fs.readFileSync(path.join(DEST, 'astryx.integration.mjs'), 'utf8').replace("components: './src/components',", "components: './src/components',\n  docs: './docs',"));

const {dependencies = {}} = pkg;
const deps = Object.fromEntries(Object.entries(dependencies).filter(([n]) => !n.startsWith('@astryxdesign/') && n !== '@stylexjs/stylex' && n !== 'react' && n !== 'react-dom'));
fs.writeFileSync(path.join(DEST, 'package.json'), JSON.stringify({
  name: '@adxs/ui', version: pkg.version, private: true, type: 'module',
  description: 'Snapshot of ADX-System/adxs-ui for the docsite (generated by scripts/sync-adxs-ui.mjs)',
  exports: {'.': './src/index.ts', ...pkg.exports},
  dependencies: deps,
  peerDependencies: {react: '>=19.0.0', 'react-dom': '>=19.0.0', '@astryxdesign/cli': '>=0.6.4'},
  astryx: {canaryOnly: true},   // private: the docsite lists a private package only on the canary target
}, null, 2) + '\n');
console.log(`adxs-ui ${pkg.version} -> ${path.relative(ROOT, DEST)}: ${docs.length} doc files, ${lines.length} export lines, ${rewritten} files with '@/' rewritten, ledger ${ledger.length} components`);
